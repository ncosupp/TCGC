const FR_TYPES: Record<string, string> = { Character: 'Personnage', Event: 'Événement', Stage: 'Lieu', Leader: 'Leader' };
const FR_ATTRS: Record<string, string> = { Slash: 'Taille', Strike: 'Frappe', Ranged: 'Distance', Special: 'Spécial', Wisdom: 'Sagesse' };

// Type de carte, attribut et couleurs dans la langue de l'interface (la valeur brute si on ne la connaît pas)
export const trType = (v: string) => (getUiLang() === 'fr' ? FR_TYPES[v] ?? v : v);
export const trAttr = (v: string) => (getUiLang() === 'fr' ? FR_ATTRS[v] ?? v : v);
export const trColor = (v: string) =>
  v.split(/[\s/;,]+/).filter(Boolean).map((c) => (hasMessage(`color.${c}`) ? t(`color.${c}` as 'color.Red').toLowerCase() : c.toLowerCase())).join(' / ');
